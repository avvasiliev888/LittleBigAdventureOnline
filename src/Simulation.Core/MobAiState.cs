namespace Simulation.Core
{
    /// <summary>
    /// Состояние серверного конечного автомата моба (PLAN §5, ADR-019):
    /// ожидание, патрулирование, преследование, атака и возврат домой.
    /// </summary>
    public enum MobAiState
    {
        /// <summary>Моб стоит и ждёт окончания паузы между точками патруля.</summary>
        Idle,

        /// <summary>Моб идёт к текущей точке патруля.</summary>
        Patrol,

        /// <summary>Моб преследует цель, которая вышла из радиуса атаки.</summary>
        Chase,

        /// <summary>Цель в радиусе атаки: моб бьёт с интервалом из конфига.</summary>
        Attack,

        /// <summary>
        /// Дальнобойный моб отходит: цель подошла ближе <c>KeepDistance</c>, а он хочет бить
        /// издалека. Отступление не отменяет удары по кулдауну.
        /// </summary>
        Retreat,

        /// <summary>Цель потеряна: моб возвращается на точку спавна и восстанавливает HP.</summary>
        Return,
    }
}
