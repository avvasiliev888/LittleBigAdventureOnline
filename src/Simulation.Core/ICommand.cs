namespace Simulation.Core
{
    /// <summary>
    /// Намерение игрока. Команда описывает то, что игрок хочет сделать, и не содержит
    /// результата: применение к состоянию — исключительно дело симуляции.
    /// </summary>
    /// <remarks>
    /// Контракт заморожен в M1 (Human-Gate): любые поля, влияющие на геймплей
    /// (скорость, урон, множители), живут в конфиге, а не в команде.
    /// </remarks>
    public interface ICommand
    {
        /// <summary>
        /// Клиентский тик, к которому относится команда. Используется для сортировки
        /// (ClientTick, Sequence) и для сопоставления с серверным подтверждением.
        /// </summary>
        uint ClientTick { get; }

        /// <summary>
        /// Монотонно возрастающий номер команды внутри клиента. Разрешает неоднозначность
        /// нескольких команд с одинаковым <see cref="ClientTick"/>.
        /// </summary>
        uint Sequence { get; }
    }
}
