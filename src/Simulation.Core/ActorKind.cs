namespace Simulation.Core
{
    /// <summary>
    /// Роль актора в правилах мира (ADR-013): только игрок теряет предметы и носит флаг враждебности,
    /// мобы подчиняются собственным правилам и в PvP не участвуют.
    /// </summary>
    public enum ActorKind : byte
    {
        /// <summary>Игрок: участвует в PvP, теряет предметы по правилам зоны.</summary>
        Player = 1,

        /// <summary>Моб или тренировочный манекен: вне правил PvP и лута игроков.</summary>
        Mob = 2,
    }
}
