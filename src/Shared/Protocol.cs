namespace Shared
{
    /// <summary>
    /// Константы протокола (ADR-004): маркер пакета и версия совместимости.
    /// </summary>
    public static class Protocol
    {
        /// <summary>
        /// Маркер начала пакета. Защищает от чтения «мусора» (чужой порт, не тот протокол).
        /// </summary>
        public const ushort Magic = 0xA1B0;

        /// <summary>
        /// Версия протокола. Поднимается при любом несовместимом изменении формата или семантики;
        /// несовпадение при handshake — отказ в соединении.
        /// </summary>
        /// <remarks>
        /// Версия 2 (M4): бинарный формат реализован впервые, запись сущности в снапшоте расширена
        /// относительно эскиза ADR-004 полями actor/resource/cooldown/respawn/spawn (ADR-008).
        /// Версия 3 (M7): в HelloAck добавлена скорость движения актора, появилось сообщение
        /// <see cref="MessageType.ServerAck"/> с подтверждением последней обработанной команды (ADR-009).
        /// Версия 4 (M8): снапшоты передаются дельтой от базового тика (<see cref="MessageType.Delta"/>),
        /// полный снапшот — по запросу при потере базы (ADR-010).
        /// Версия 5 (M13): в кодек команд добавлены смена снаряжения и сбор ресурса (ADR-014).
        /// Версия 6 (M14): в кодек команд добавлены крафт и торговля с NPC (ADR-016).
        /// Версия 7 (M15): в кодек команд добавлен сбор лута из трупа моба (ADR-018).
        /// Версия 8 (M16): снапшот содержит зону, Славу, серебро, экипировку, флаг враждебности,
        /// способность/скорость и трупы; клиент рисует HUD и мир без доступа к серверу (ADR-020).
        /// Версия 9 (M17): добавлена debug-команда телепорта к точке мировой карты (ADR-023).
        /// Формат снапшота не менялся; команда принимается только при включённом debug-режиме сервера.
        /// </remarks>
        public const ushort Version = 9;
    }

    /// <summary>
    /// Тип сообщения в заголовке пакета. Значения фиксируются в M1 и меняются только с версией протокола.
    /// </summary>
    public enum MessageType : byte
    {
        /// <summary>Клиент представляется серверу и передаёт версию протокола.</summary>
        Hello = 1,

        /// <summary>Сервер принимает соединение или отказывает с причиной.</summary>
        HelloAck = 2,

        /// <summary>Команда игрока (надёжная доставка).</summary>
        Command = 3,

        /// <summary>Полный снапшот мира (ненадёжная доставка).</summary>
        Snapshot = 4,

        /// <summary>Дельта относительно <c>baseTick</c> (M8).</summary>
        Delta = 5,

        /// <summary>Запрос полного снапшота, если база для дельты потеряна.</summary>
        FullSnapshotRequest = 6,

        /// <summary>
        /// Подтверждение сервера: какой тик и какая последняя команда клиента обработаны (M7, ADR-009).
        /// Надёжная доставка; клиент использует пару «тик + sequence» для реконсиляции.
        /// </summary>
        ServerAck = 7,
    }
}
